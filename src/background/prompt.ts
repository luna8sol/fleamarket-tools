/**
 * 表記ルール（用語の統一）
 *
 * 既存の出品では同じ説明文の中で「下さい」と「ください」が混在していたため、
 * 補助動詞・形式名詞は仮名書きに統一します。
 */
const WRITING_RULES = [
  '- 「下さい」ではなく「ください」を使う（本動詞の「下さい」も使わない）。',
  '- 補助動詞は仮名書きにする。「頂く」「頂ければ」→「いただく」「いただければ」。',
  '- 形式名詞は仮名書きにする。「の為」→「のため」、「事」→「こと」。',
  '- 「致します」ではなく「いたします」を使う。',
  '- 可能形を誤用しない。「応じれない」ではなく「応じられない」。',
  '- 状態の語順は「新品未使用・未開封」に固定する（「新品未開封未使用」と書かない）。',
  '- 箇条書きの行頭は「・」。前の行の続きを書くときは行頭を全角スペース1つでそろえる。',
  '- 属性の区切りは「...」（半角ピリオド3つ）に統一する。「：」「···」は使わない。',
  '- 体言止めにしない。文は「です」「ます」で終える。',
  '- 半角カナ・機種依存文字・絵文字は使わない。',
].join('\n');

