/**
 * 本文の照合に使う軽量ハッシュと改行の正規化（両拡張で共通）。
 *
 * 説明文の一括置換で、原本・確定版・保存後の本文が**一字一句同じか**を照合するために使う。
 * 文字数だけでは並び替えや置換の取りこぼしを見分けられないため、文字数と併せて比較する。
 *
 * ハッシュの**文字列表記は拡張ごとに違う**（メルカリ用は 10 進、ラクマ用は 8 桁の 16 進）。
 * どちらも保存済みの記録に入っていて照合に使われるため、ここでは数値を返すだけにし、
 * 表記は各拡張側で付ける。
 */

/**
 * FNV-1a（32bit）。依存を増やさずに済む軽量なハッシュ。
 *
 * - `charCodeAt` 単位（UTF-16 コードユニット）で畳み込む。サロゲートペアも 2 単位として
 *   一貫して扱われるので、同じ実装同士で比べる限り結果は一致する。
 * - 暗号用途ではない。改ざん検知ではなく「取得後に変わっていないか」の判定に使う。
 *
 * @returns 32bit 符号なし整数
 */
export function fnv1a32(text: string): number {
  let hash = 0x811c9dc5;
  for (let i = 0; i < text.length; i++) {
    hash ^= text.charCodeAt(i);
    hash = Math.imul(hash, 0x01000193) >>> 0;
  }
  return hash;
}

/**
 * 改行コードだけを LF に揃える（CRLF / CR → LF）。改行以外の文字は一切変えない。
 *
 * 確定版は LF で持っているが、サーバーから返る本文は CRLF になりうるため、
 * 照合の前にこれを通す。
 */
export function normalizeLineBreaks(text: string): string {
  return text.replace(/\r\n?/g, '\n');
}
